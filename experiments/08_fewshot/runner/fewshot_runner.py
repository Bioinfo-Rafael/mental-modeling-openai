@dataclass(frozen=True)
class ScorePattern:
    name: str
    correct_scores: tuple[int, ...]
    incorrect_scores: tuple[int, ...]


@dataclass(frozen=True)
class FewshotExperiment:
    name: str
    models: tuple[str, ...]
    tasks: tuple[str, ...]
    metric: str
    histories: tuple[int, ...]
    shot_counts: tuple[int, ...]
    score_patterns: tuple[ScorePattern, ...]
    n: int = 3
    seed: int = 42
    selection_policy: str = "seeded"


def digest(value):
    return hashlib.sha256(value.encode('utf-8')).hexdigest()


def json_text(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, allow_nan=False)


def read_json(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False)+'\n', encoding='utf-8')


def validate_spec(spec):
    if spec.selection_policy not in {'seeded', 'balanced_next'}:
        raise ValueError('Unknown selection policy')
    if spec.selection_policy == 'balanced_next' and max(spec.shot_counts) > 12:
        raise ValueError('Balanced fixed pools support at most 12 examples')
    if spec.name != '08_fewshot' or spec.metric != 'next-action':
        raise ValueError('08 currently evaluates next-action only')
    for items in (spec.models, spec.tasks, spec.histories, spec.shot_counts):
        if not items or len(set(items)) != len(items):
            raise ValueError('Experiment axes must be nonempty and unique')
    if not set(spec.models) <= {'terra', 'luna'} or not set(spec.tasks) <= set(common.TASKS):
        raise ValueError('Unsupported model/task')
    if any(type(h) is not int or h < 1 for h in spec.histories):
        raise ValueError('H must be a positive integer')
    if any(type(n) is not int or n < 2 or n % 2 for n in spec.shot_counts):
        raise ValueError('Shot counts must be positive even integers')
    if type(spec.n) is not int or spec.n < 1 or type(spec.seed) is not int or not 0 <= spec.seed <= 0xffffffff:
        raise ValueError('N must be positive and seed must be uint32')
    if not spec.score_patterns or len({p.name for p in spec.score_patterns}) != len(spec.score_patterns):
        raise ValueError('Score patterns must be unique and nonempty')
    for p in spec.score_patterns:
        if not p.name or not all(c.isalnum() or c in '_-' for c in p.name):
            raise ValueError('Invalid pattern name')
        for scores in (p.correct_scores, p.incorrect_scores):
            if not isinstance(scores, tuple) or not scores or len(set(scores)) != len(scores) or any(type(s) is not int or s not in (1,2,3,4) for s in scores):
                raise ValueError('Allowed scores must be nonempty unique tuples of integers 1–4')


def discover_inputs(explicit, data_dir):
    if explicit:
        paths = [(Path(p) if Path(p).is_absolute() else HERE / p).resolve() for p in explicit]
        if len(set(paths)) != len(paths):
            raise ValueError('Input files are duplicated')
        return paths
    paths = []
    for path in sorted(data_dir.glob('*.json')):
        if path.name in {'examples.json', 'validation.json'}:
            continue
        try:
            payload = read_json(path)
        except (OSError, ValueError):
            if path.name.startswith('selected_examples'):
                raise ValueError(f'選択済みJSONを読み込めません: {path.name}')
            continue
        if isinstance(payload, dict) and payload.get('kind') == 'candidate_pool':
            paths.append(path.resolve())
    if len(paths) > 1:
        raise ValueError('候補集JSONが複数あります。run.pyのINPUT_FILESまたは--inputで指定してください: '
                         + ', '.join(p.name for p in paths))
    return paths


def load_candidates(paths, catalog_path):
    if not paths:
        return [], {}, 0
    catalog = read_json(catalog_path)
    catalog_by_id = {e['query_id']: e for e in catalog}
    if len(catalog_by_id) != len(catalog):
        raise ValueError('共通データのquery_idが重複しています')
    hashes = {str(catalog_path.resolve()): file_sha256(catalog_path)}
    chosen, duplicates = {}, 0
    for path in paths:
        hashes[str(path)] = file_sha256(path)
        payload = read_json(path)
        if not isinstance(payload, dict) or payload.get('schema_version') != 1 or payload.get('kind') not in {'candidate_pool', 'fewshot_subset'}:
            raise ValueError(f'07から出力した候補集／subset JSONが必要です: {path.name}')
        if not isinstance(payload.get('examples'), list) or not payload['examples']:
            raise ValueError(f'候補集に選択済みの例がありません: {path.name}')
        local_ids = set()
        for index, e in enumerate(payload['examples']):
            if not isinstance(e, dict):
                raise ValueError(f'Invalid example at {path.name}:{index}')
            qid = e.get('query_id')
            if qid in local_ids:
                raise ValueError(f'同じファイル内にIDの重複があります: {path.name}:{qid}')
            local_ids.add(qid)
            original = catalog_by_id.get(qid)
            if original is None:
                raise ValueError(f'共通データにないquery_id: {qid}')
            for key, value in original.items():
                if key not in {'example_type', 'note', 'selection_order'} and e.get(key) != value:
                    raise ValueError(f'元データと不一致: {path.name}, {qid}, {key}')
            if 'system_prompt' in e or e.get('example_type') not in {'correct', 'incorrect'} or not e.get('response_available'):
                raise ValueError(f'選択区分／回答が無効です: {qid}')
            clean = {**original, 'example_type': e['example_type'], 'note': str(e.get('note', ''))}
            if qid in chosen:
                if chosen[qid]['example_type'] != clean['example_type'] or chosen[qid]['note'] != clean['note']:
                    raise ValueError(f'複数ファイルで選択区分／メモが競合しています: {qid}')
                duplicates += 1
            else:
                chosen[qid] = clean
    return list(chosen.values()), hashes, duplicates


def conditions(spec):
    rows = []
    for model, task, H, shots, pattern in itertools.product(spec.models, spec.tasks, spec.histories, spec.shot_counts, spec.score_patterns):
        rows.append(dict(condition_id=f'{model}__{task}__next-action__H{H}__shots{shots}__{pattern.name}',
                         model_alias=model, model=common.MODELS[model], task=task, metric=spec.metric,
                         H=H, shots=shots, score_pattern=pattern.name,
                         correct_scores=list(pattern.correct_scores), incorrect_scores=list(pattern.incorrect_scores), n=spec.n))
    return rows


MODEL_ORDER=('sol','terra','luna','3.5')


def example_preference(e):
    return (e['metric']!='next-action',e['H'],e['episode_path'],e['query_index'],e['ordinal'],e['query_id'])


def balanced_pool(pool, pattern, kind):
    """Six per role; fixed model quotas, minimize last-action, retain score contrast."""
    quotas = {'sol':2,'terra':2,'luna':2,'3.5':0} if pattern.name=='pattern1' and kind=='correct' else {'sol':1,'terra':1,'luna':2,'3.5':2}
    required_score = 4 if pattern.name=='pattern1' and kind=='incorrect' else 2 if pattern.name=='pattern2' and kind=='correct' else None
    grouped={model:sorted((e for e in pool if e['model']==model),key=example_preference) for model in MODEL_ORDER}
    picked={model:grouped[model][:quotas[model]] for model in MODEL_ORDER}
    flat=[e for group in picked.values() for e in group]
    if len(flat)==6 and required_score is not None and not any(e['reasoning_score']==required_score for e in flat):
        alternatives=[]
        for model in MODEL_ORDER:
            for candidate in grouped[model]:
                if candidate['reasoning_score']!=required_score:
                    continue
                for i in range(len(picked[model])):
                    variant={m:list(v) for m,v in picked.items()}
                    variant[model][i]=candidate
                    rows=[e for group in variant.values() for e in group]
                    key=(sum(e['metric']!='next-action' for e in rows),tuple(sorted(example_preference(e) for e in rows)))
                    alternatives.append((key,variant))
        if not alternatives:
            # Expose a shortage instead of dropping the agreed score-contrast requirement.
            picked[next(m for m in reversed(MODEL_ORDER) if picked[m])].pop()
        else:
            picked=min(alternatives,key=lambda item:item[0])[1]
    for model in MODEL_ORDER:
        picked[model].sort(key=example_preference)
    # Round-robin preserves model balance in the prefixes used by 4/8-shot runs.
    return [picked[model][i] for i in range(2) for model in MODEL_ORDER if len(picked[model])>i]


def role_pool(spec, examples, task, pattern, kind):
    pool=[e for e in examples if e['task']==task and e['example_type']==kind and e['reasoning_score'] in getattr(pattern,kind+'_scores')]
    if spec.selection_policy=='balanced_next':
        return balanced_pool(pool,pattern,kind),len(pool)
    return sorted(pool,key=lambda e:(prepare.rank(spec.seed,e['query_id']),e['query_id'])),len(pool)


def candidate_inventory(spec, examples):
    rows=[]
    required=6 if spec.selection_policy=="balanced_next" else max(spec.shot_counts)//2
    for task,pattern,kind in itertools.product(spec.tasks,spec.score_patterns,('correct','incorrect')):
        pool,original_count=role_pool(spec,examples,task,pattern,kind)
        rows.append(dict(task=task,score_pattern=pattern.name,example_type=kind,
                         allowed_scores=list(getattr(pattern,kind+'_scores')),original_available=original_count,
                         required=required,available=len(pool),missing=max(0,required-len(pool))))
    return rows


def choose_demonstrations(spec, examples):
    bundles={}
    for task,pattern in itertools.product(spec.tasks,spec.score_patterns):
        pools={kind:role_pool(spec,examples,task,pattern,kind)[0] for kind in ('correct','incorrect')}
        for count in spec.shot_counts:
            k=count//2
            if any(len(pool)<k for pool in pools.values()):
                raise ValueError(f'候補不足（モデル配分・Score条件を含む）: {task}/{pattern.name}/{count}')
            bundles[(task,pattern.name,count)]=[pools[kind][i] for i in range(k) for kind in ('correct','incorrect')]
    return bundles


def select_targets(spec, examples, data_root=DEFAULT_DATA_ROOT):
    """Same held-out episode/index across H and every other evaluation axis."""
    excluded_paths = {(ROOT/e['episode_path']).resolve() for e in examples}
    excluded_hashes = {e['episode_sha256'] for e in examples}
    sources = sorted(discover_episodes(data_root), key=lambda s:str(s.path))
    targets = {}
    for task in spec.tasks:
        chosen = []
        question = JOINT_QUESTIONS[task][spec.metric]
        for source in (s for s in sources if s.task==task):
            if source.path.resolve() in excluded_paths or file_sha256(source.path) in excluded_hashes:
                continue
            highest = max(spec.histories)
            anchor = list(itertools.islice(build_prompt_queries(source,metric=spec.metric,question_name=question,
                                history_size=common.history_size(highest)),spec.n-len(chosen)))
            if not anchor:
                continue
            by_h = {highest:{q.query_index:q for q in anchor}}
            wanted = set(by_h[highest])
            for H in spec.histories:
                if H==highest:
                    continue
                by_h[H] = {}
                for q in build_prompt_queries(source,metric=spec.metric,question_name=question,history_size=common.history_size(H)):
                    if q.query_index in wanted:
                        by_h[H][q.query_index]=q
                    if wanted==set(by_h[H]):
                        break
                if set(by_h[H]) != wanted:
                    raise ValueError('H間で同じ評価問題を選べません')
            chosen.extend({H:by_h[H][q.query_index] for H in spec.histories} for q in anchor)
            if len(chosen)==spec.n:
                break
        if len(chosen)!=spec.n:
            raise ValueError(f'{task}: 例と別episodeの有効問題が不足（必要{spec.n} / {len(chosen)}）')
        targets[task]=chosen
    return targets


def compose_user(examples, target_user):
    if not target_user.startswith(MARKER):
        raise ValueError('元のuser promptが想定した開始文と一致しません')
    prefix = prepare.prompt_text(examples).rstrip()+TARGET_BOUNDARY
    return prefix+target_user, len(prefix)


def make_plan(spec, examples, input_hashes, data_root=DEFAULT_DATA_ROOT):
    #@Rafaメモ: bundlesは、実験条件をkeyとし、few-shotに用いる例をvalueとするdictを返す。
    bundles=choose_demonstrations(spec,examples)
    targets=select_targets(spec,examples,data_root)
    import tiktoken
    encoding=tiktoken.get_encoding('o200k_base')
    rows=[]
    for condition in conditions(spec):
        #@Rafaメモ:このshotsがconditionに対応するfew-shotの例
        shots=bundles[(condition['task'],condition['score_pattern'],condition['shots'])]
        for ordinal, aligned in enumerate(targets[condition['task']]):
            q=aligned[condition['H']]
            if q.history_end-q.history_start != condition['H']:
                raise ValueError('History length mismatch')
            #@Rafaメモ: compose_user関数で、few-shotの例と、元のuser promptを結合して、最終的なuser promptを生成する
            user,offset=compose_user(shots,q.user_prompt)
            request=common.expected_api_request(condition['model'],q.system_prompt,user)
            base={**condition,'ordinal':ordinal,'episode_path':str(q.episode_path.relative_to(ROOT)),
                  'episode_sha256':q.dataset_sha256,'query_index':q.query_index,
                  'history_start':q.history_start,'history_end_exclusive':q.history_end,
                  'upstream_history_size':common.history_size(condition['H']),
                  'question_name':JOINT_QUESTIONS[condition['task']][spec.metric],
                  'example_ids':[e['query_id'] for e in shots],
                  'system_prompt_sha256':digest(q.system_prompt),'user_prompt_sha256':digest(user),
                  'target_user_prompt_sha256':digest(q.user_prompt)}
            base['query_id']=digest(json_text(base))
            rows.append({**base,'system_prompt':q.system_prompt,'user_prompt':user,
                         'target_user_prompt':q.user_prompt,'target_offset':offset,'request':request,
                         'input_content_tokens':len(encoding.encode(q.system_prompt,disallowed_special=()))+len(encoding.encode(user,disallowed_special=())),
                         'tokenizer':'o200k_base','token_note':'local content tokens only; API message overhead excluded',
                         'prompt_txt':f'prompts/{condition["condition_id"]}/query_{ordinal+1:02d}.txt'})
            input_hashes[str(q.episode_path)]=q.dataset_sha256
    if len({r['query_id'] for r in rows})!=len(rows):
        raise ValueError('Duplicate few-shot query identities')
    return rows


def write_csv(path, rows, fields):
    with path.open('w',newline='',encoding='utf-8-sig') as handle:
        writer=csv.DictWriter(handle,fieldnames=fields,extrasaction='ignore')
        writer.writeheader();writer.writerows(rows)


def preview(directory, manifest, examples):
    payload={'manifest':manifest,'examples':{e['query_id']:e for e in examples}}
    template=(HERE/'results/dry_run/preview_template.html').read_text(encoding='utf-8')
    directory.joinpath('preview.html').write_text(template.replace('__DATASET__',json.dumps(payload,ensure_ascii=False,allow_nan=False).replace('<','\\u003c')),encoding='utf-8')


def save_outputs(directory, manifest, examples):
    directory.mkdir(parents=True,exist_ok=False)
    for q in manifest['queries']:
        path=directory/q['prompt_txt'];path.parent.mkdir(parents=True,exist_ok=True)
        header=f"{q['condition_id']} / query {q['ordinal']+1}\nquery_id: {q['query_id']}\n\n"
        path.write_text(header+'SYSTEM MESSAGE\n==============\n'+q['system_prompt']+'\n\nUSER MESSAGE\n============\n'+q['user_prompt']+'\n',encoding='utf-8')
    write_json(directory/'manifest.json',manifest)
    fields=['condition_id','model_alias','task','metric','H','shots','score_pattern','correct_scores','incorrect_scores','n']
    write_csv(directory/'conditions.csv',manifest['conditions'],fields)
    write_csv(directory/'manifest.csv',manifest['queries'],fields+['ordinal','query_id','episode_path','query_index','input_content_tokens','prompt_txt'])
    write_csv(directory/'candidate_inventory.csv',manifest['candidate_inventory'],['task','score_pattern','example_type','allowed_scores','original_available','required','available','missing'])
    write_json(directory/'selected_candidates.json',{'schema_version':1,'kind':'candidate_pool','examples':examples})
    if manifest['queries']:
        lookup={e['query_id']:e for e in examples}
        groups=[]
        for task in manifest['config']['tasks']:
            for pattern in manifest['config']['score_patterns']:
                q=next(q for q in manifest['queries'] if q['task']==task and q['score_pattern']==pattern['name'] and q['shots']==max(manifest['config']['shot_counts']))
                groups.append(dict(task=task,score_pattern=pattern['name'],examples=[lookup[key] for key in q['example_ids']]))
        write_json(directory/'pattern_examples.json',dict(schema_version=1,kind='fixed_pattern_pools',selection_policy=manifest['config']['selection_policy'],groups=groups))
    preview(directory,manifest,examples)
    messages='\n'.join('- '+s for s in manifest['messages']) or '- 全条件のプロンプトを生成しました。'
    directory.joinpath('README.md').write_text(
        f"# 08 Few-shot dry-run\n\nStatus: `{manifest['status']}`\n\n"
        f"予定: {manifest['planned_conditions']}条件 × {manifest['config']['n']}問 = {manifest['planned_queries']}件。"
        f"生成済み: {len(manifest['queries'])}件。API呼び出し: 0。\n\n{messages}\n\n"
        "[preview.html](preview.html)で送信予定system/user全文を確認できます。改行はそのまま表示します。\n\n"
        "- `prompts/`: 1件ごとのTXT（ready時のみ）\n- `manifest.json`: 全条件・送信予定request・使用例ID・入力SHA\n"
        "- `candidate_inventory.csv`: Task・Score・区分別の必要数と候補数\n"
        "- `selected_candidates.json`: 読み込んだ候補のスナップショット\n\n"
        "これは計画のみで、送信・回答取得・精度評価は行っていません。\n",encoding='utf-8')


def run(spec, argv=None, *, input_files=()):
    parser=argparse.ArgumentParser(description='08 Few-shot next-action: dry run by default')
    parser.add_argument('--dry-run',action='store_true',help='Default; accepted for clarity')
    parser.add_argument('--execute',action='store_true',help='Send the reviewed requests to the API')
    parser.add_argument('--confirm-paid-api',action='store_true')
    parser.add_argument('--resume',action='store_true',help='Send only unattempted queries from the saved API run')
    parser.add_argument('--input',nargs='+',type=Path,help='Explicit selected-example export(s); relative paths start at 08_fewshot/')
    parser.add_argument('--task',nargs='+',choices=common.TASKS)
    parser.add_argument('--model',nargs='+',choices=('terra','luna'))
    parser.add_argument('--history',nargs='+',type=int)
    parser.add_argument('--shots',nargs='+',type=int)
    args=parser.parse_args(argv)
    if args.execute != args.confirm_paid_api:
        parser.error('API execution requires both --execute and --confirm-paid-api')
    if args.dry_run and args.execute:
        parser.error('--dry-run and --execute cannot be combined')
    if args.resume and not args.execute:
        parser.error('--resume requires --execute --confirm-paid-api')
    for name,field in [('task','tasks'),('model','models'),('history','histories'),('shots','shot_counts')]:
        if getattr(args,name) is not None:
            spec=replace(spec,**{field:tuple(getattr(args,name))})
    try:
        validate_spec(spec)
    except ValueError as exc:
        parser.error(str(exc))
    # @Rafaメモ: conditions関数は実験条件についてその全ての組み合わせを要素にするリストを返す。要素はdictでvalueとして条件を持つ
    all_conditions=conditions(spec)
    # @Rafaメモ: manifestは実験の計画をまとめるためだけのdict
    manifest=dict(schema_version=2,experiment=spec.name,mode='dry_run',status='input_required',
                  config=asdict(spec),conditions=all_conditions,planned_conditions=len(all_conditions),
                  planned_queries=len(all_conditions)*spec.n,generated_queries=0,api_requests_made=0,
                  queries=[],candidate_inventory=[],input_files=[],input_sha256={},messages=[],
                  selection=spec.selection_policy+'; same-task; nested prefixes; alternate correct/incorrect',
                  target_selection='path-sorted held-out episodes, same indices across H/models/shot counts/score patterns',
                  source_code_sha256={str(p.relative_to(ROOT)):file_sha256(p) for p in
                                      (HERE/'run.py',Path(__file__),HERE/'data_prep/prepare_prompt.py',HERE/'results/dry_run/preview_template.html')})
    examples=[]
    try:
        paths=discover_inputs(args.input or input_files,HERE/'data_prep')
        manifest['input_files']=[str(p) for p in paths]
        examples,hashes,duplicates=load_candidates(paths,HERE/'data_prep/examples.json')
        manifest['input_sha256']=hashes
        manifest['duplicate_examples_removed']=duplicates
        manifest['candidate_inventory']=candidate_inventory(spec,examples)
        if not paths:
            manifest['messages'].append('選択済みJSONがありません。07の「候補集JSON（全選択）」を08_fewshot/data_prep/へ保存して再実行してください。examples.jsonの未選択例は使いません。')
        elif any(row['missing'] for row in manifest['candidate_inventory']):
            manifest['status']='insufficient_candidates'
            manifest['messages'].append('候補が不足しています。candidate_inventory.csv／preview.htmlでTask・区分・Scoreごとの不足数を確認してください。')
        else:
            #@Rafaメモ: このmake_plan関数で、実験条件ごとに、system/user promptを生成して、manifest['queries']に格納する
            manifest['queries']=make_plan(spec,examples,hashes)
            manifest['generated_queries']=len(manifest['queries'])
            for path,expected in hashes.items():
                if file_sha256(Path(path))!=expected:
                    raise ValueError(f'入力が生成中に変更されました: {path}')
            manifest['status']='ready'
    except (OSError,ValueError,KeyError,TypeError) as exc:
        manifest['status']='invalid_input'
        manifest['queries']=[];manifest['generated_queries']=0
        manifest['messages'].append(str(exc))
    if not manifest['candidate_inventory']:
        manifest['candidate_inventory']=candidate_inventory(spec,examples)
    now=datetime.now(ZoneInfo('Asia/Tokyo'))
    manifest['created_at_jst']=now.isoformat()
    if args.execute:
        executor=import_module('experiments.08_fewshot.runner.api_execution')
        try:
            return executor.execute(manifest,resume=args.resume)
        except (Exception,common.SafetyStop,KeyboardInterrupt) as exc:
            print('Stopped:',common.redact(str(exc) or type(exc).__name__),file=sys.stderr)
            return 2
    directory=common.output_path(HERE/'results/dry_run')
    staging=directory.with_name(f'.dry_run_{uuid.uuid4().hex[:8]}')
    try:
        save_outputs(staging,manifest,examples)
        # The editable template lives inside the output directory; preserve it
        # before replacing generated dry-run artifacts.
        shutil.copy2(HERE/'results/dry_run/preview_template.html', staging/'preview_template.html')
        if directory.is_symlink():
            raise ValueError('Refusing to replace a symlink output directory')
        if directory.exists():
            shutil.rmtree(directory)
        staging.rename(directory)
    finally:
        if staging.exists():
            shutil.rmtree(staging)
